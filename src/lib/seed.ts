function items(
  kind: ItemKind,
  category: string,
  rows: [id: string, name: string, unit: string, price: number, stock?: number][],
): CatalogItem[] {
  return rows.map(([id, name, unit, price, stock]) => ({
    id,
    kind,
    category,
    name,
    description: DESCRIPTIONS[id],
    unit,
    price: toSum(price),
    stock: stock ?? null,
  }));
}

